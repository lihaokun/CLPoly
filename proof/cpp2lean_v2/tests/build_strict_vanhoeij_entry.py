"""Explicit repaired try-recombine entry; not an AST translation/equivalence proof."""
from pathlib import Path
import argparse

OUT = Path(__file__).resolve().parents[2] / "lean/CLPoly/Generated/StrictVanHoeijEntry.lean"


def generate() -> str:
    return r'''-- Generated by build_strict_vanhoeij_entry.py; edit the template.
import CLPoly.Generated.StrictVanHoeijController
import CLPoly.Generated.StrictVanHoeijParameters

set_option autoImplicit false

namespace Generated.StrictVanHoeijEntry
open StrictRecombine StrictVanHoeij StrictVanHoeijParameters StrictVanHoeijController

/-- Only erased call-entry obligations, with executable operations fixed below. -/
structure EntryExecution where
  controller : ControllerExecution
  cld : CldRawOps
  cldSize : ∀ f lifted modulus output,
    cldPolys cld f lifted modulus = .ok output → output.size = lifted.size
  truncateSize : ∀ input divisor output,
    truncateCld input divisor = .ok output → output.size = input.size
  parameterModulus : ∀ count height modulus parameters,
    selectParameters count height modulus = some parameters → parameters.modulus ≠ 0
  initialBound : ∀ width : Int32, (min (2 : Int32) width).toInt ≤ width.toInt

/-- Source try-recombine entry. The count range is an explicit erased source
precondition, not an extra runtime test. The outer Hensel retry is separate. -/
def tryRecombine (execution : EntryExecution) (f : SparsePolyZZ)
    (lifted : Array SparsePolyZZ) (modulus : ZZ) (countFits : lifted.size < 2 ^ 31) :
    RawExec VanHoeijResult := do
  let count := Int32.ofNat lifted.size
  if 2 ≤ count ∧ 1 < modulus then
    let height ← cldBound f
    let singletons ← singletonGroups count
    let checked ← validatePartition f lifted modulus singletons {}
    if checked.1 then .ok checked.2
    else
      match hp : selectParameters count height modulus with
      | none => .ok checked.2
      | some parameters =>
        match hc : cldPolys execution.cld f lifted modulus with
        | .error fault => .error fault
        | .ok original =>
          match ht : truncateCld original parameters.divisor with
          | .error fault => .error fault
          | .ok truncated =>
            let width := cldWidth truncated
            let target := min (2 : Int32) width
            have countSize : count.toInt.toNat = truncated.size := by
              have hr : count.toInt.toNat = lifted.size := by
                dsimp only [count]
                rw [Int32.toInt_ofNat_of_lt countFits]
                exact Int.toNat_natCast _
              exact hr.trans ((execution.cldSize f lifted modulus original hc).symm.trans
                (execution.truncateSize original parameters.divisor truncated ht).symm)
            columnLoop execution.controller f lifted truncated modulus parameters.modulus 32
              parameters.residual count width target countSize (by decide)
              (execution.parameterModulus count height modulus parameters hp)
              (execution.initialBound width) checked.2
  else .error .assertionFailure

end Generated.StrictVanHoeijEntry
'''


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = generate()
    if args.check:
        if not OUT.exists() or OUT.read_text() != source:
            raise SystemExit(f"generated output is stale: {OUT}")
    else:
        OUT.write_text(source)
