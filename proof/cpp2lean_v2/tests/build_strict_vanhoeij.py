"""Strict control-flow model for the repaired van Hoeij helpers.

The old StrictRecombine controller remains a legacy model during migration.
This explicit template is not an AST translation or a correspondence proof.
"""

from pathlib import Path
import argparse

OUT = Path(__file__).resolve().parents[2] / "lean/CLPoly/Generated/StrictVanHoeij.lean"


def generate() -> str:
    return r'''-- Generated by build_strict_vanhoeij.py; edit the template.
import CLPoly.Generated.StrictRecombine

set_option autoImplicit false

namespace Generated.StrictVanHoeij
open StrictRecombine
abbrev LLLMatrix := StrictRecombine.LLLMatrix

/-- Source L1 loop: copy, conditional negate, then accumulate each term. -/
def normL1Loop (f : SparsePolyZZ) (index : Nat) (sum : ZZ) : ZZ :=
  if hi : index < f.size then
    let coefficient := f[index].2
    let magnitude := if coefficient < 0 then -coefficient else coefficient
    normL1Loop f (index + 1) (sum + magnitude)
  else sum
termination_by f.size - index
decreasing_by omega

def normL1 (f : SparsePolyZZ) : ZZ := normL1Loop f 0 0

/-- Preserve the source int cast, assertion and integer left shift. -/
def cldBound (f : SparsePolyZZ) : RawExec ZZ :=
  let n : Int32 := (get_deg f).toInt32
  if 0 < n then
    .ok (n.toInt * ((1 : ZZ) <<< (n - 1).toInt.toNat) * normL1 f)
  else .error .assertionFailure

/-- The source loop cannot overflow its signed index while index < count. -/
theorem int32_increment_toInt_of_lt (index count : Int32) (hlt : index < count) :
    (index + 1).toInt = index.toInt + 1 := by
  rw [Int32.toInt_add]
  change (index.toInt + 1).bmod (2 ^ 32) = index.toInt + 1
  have hl := Int32.lt_iff_toInt_lt.mp hlt
  have hi := Int32.le_toInt index
  have hc := Int32.toInt_lt count
  apply Int.bmod_eq_of_le <;> omega

def singletonGroupsLoop (count index : Int32) (groups : Array (Array Int32)) :
    RawExec (Array (Array Int32)) :=
  if hlt : index < count then
    if 0 ≤ index then
      if hi : index.toInt64.toNat < groups.size then
        singletonGroupsLoop count (index + 1)
          (groups.set index.toInt64.toNat (groups[index.toInt64.toNat].push index))
      else .error (.outOfBounds index.toInt64.toNat groups.size)
    else .error .assertionFailure
  else .ok groups
termination_by (count.toInt - index.toInt).toNat
decreasing_by
  rw [int32_increment_toInt_of_lt index count hlt]
  have hl := Int32.lt_iff_toInt_lt.mp hlt
  omega

def singletonGroups (count : Int32) : RawExec (Array (Array Int32)) :=
  if 0 ≤ count then singletonGroupsLoop count 0 (Array.replicate count.toInt.toNat #[])
  else .error .assertionFailure

def nextCldTarget (target width : Int32) : Int32 :=
  if target > width / 2 then width else 2 * target

structure VanHoeijResult where
  factors : Array SparsePolyZZ := #[]
  complete : Bool := false
  cldColumns : Int32 := 0
  retainedRows : Int32 := 0

/-- Both mutations in the source group loop: modular product then degree sum. -/
def partitionProductLoop (group : Array Int32) (lifted : Array SparsePolyZZ)
    (modulus : ZZ) (index : Nat) (product : SparsePolyZZ) (degree : Int64) :
    RawExec (SparsePolyZZ × Int64) := do
  if hi : index < group.size then
    let source := group[index]
    if source < 0 then .error .arithmeticDomain
    else
      let position := source.toInt64.toNat
      if hp : position < lifted.size then
        let product' ← multiplyNormalizeModRaw product lifted[position] modulus
        partitionProductLoop group lifted modulus (index + 1) product'
          (degree + get_deg lifted[position])
      else .error (.outOfBounds position lifted.size)
  else .ok (product, degree)
termination_by group.size - index
decreasing_by omega

/-- Fail the entire partition on the first failed group; publish no prefix. -/
def validatePartitionLoop (lifted : Array SparsePolyZZ) (modulus : ZZ)
    (groups : Array (Array Int32)) (index : Nat)
    (remaining : SparsePolyZZ) (factors : Array SparsePolyZZ) :
    RawExec (Option (Array SparsePolyZZ)) := do
  if hi : index < groups.size then
    if hr : 0 < remaining.size then
      if get_deg remaining ≤ 0 then .ok none
      else
        let initial : SparsePolyZZ := #[(⟨0⟩, remaining[0].2)]
        let (product, degree) ← partitionProductLoop groups[index] lifted modulus 0 initial 0
        let symmetric ← symmetricModRaw product modulus
        let (_, factor) ← primitiveRaw symmetric
        if factor.isEmpty || get_deg factor != degree || degree ≤ 0 then .ok none
        else
          let (quotient, remainder) ← exactDivmodRaw remaining factor
          if remainder.isEmpty then
            validatePartitionLoop lifted modulus groups (index + 1) quotient (factors.push factor)
          else .ok none
    else .ok none
  else
    if remaining.size != 1 || get_deg remaining != 0 || remaining[0]!.2 != 1 then .ok none
    else .ok (some (sortFactorsByDegree factors))
termination_by groups.size - index
decreasing_by omega

def validatePartition (f : SparsePolyZZ) (lifted : Array SparsePolyZZ)
    (modulus : ZZ) (groups : Array (Array Int32)) (answer : VanHoeijResult) :
    RawExec (Bool × VanHoeijResult) := do
  if groups.isEmpty then .ok (false, answer)
  else
    match ← validatePartitionLoop lifted modulus groups 0 f #[] with
    | none => .ok (false, answer)
    | some factors => .ok (true, { answer with factors := factors, complete := true })

/-- Source loop assigning C_i[k] to column r+j of existing factor rows. -/
def fillCldColumnLoop (cld : Array SparsePolyZZ) (degree column index : Nat)
    (matrix : LLLMatrix) : RawExec LLLMatrix :=
  if hi : index < cld.size then
    if hm : index < matrix.size then
      if hc : column < matrix[index].size then
        fillCldColumnLoop cld degree column (index + 1)
          (matrix.set index (matrix[index].set column (sparseCoeff cld[index] degree)))
      else .error (.outOfBounds column matrix[index].size)
    else .error (.outOfBounds index matrix.size)
  else .ok matrix
termination_by cld.size - index
decreasing_by omega

/-- Repaired [sI | C; 0 | mI] row basis; m is an actual input. -/
def appendCldColumn (matrix : LLLMatrix) (cld : Array SparsePolyZZ)
    (existingColumns spiralDegree : Nat) (modulus : ZZ) : RawExec LLLMatrix := do
  let extended ← appendZeroColumn matrix
  let column := cld.size + existingColumns
  let filled ← fillCldColumnLoop cld spiralDegree column 0 extended
  let row := zeroMatrixRow (column + 1)
  if hc : column < row.size then
    .ok (filled.push (row.set column modulus))
  else .error (.outOfBounds column row.size)

def buildCldMatrixLoop (cld : Array SparsePolyZZ) (current target width : Nat)
    (modulus : ZZ) : (added : Nat) → LLLMatrix → RawExec (LLLMatrix × Nat)
  | added, matrix =>
    if added < target then
      let k := current + added
      if k < width then
        let degree := if k % 2 = 0 then k / 2 else width - 1 - (k - 1) / 2
        match appendCldColumn matrix cld k degree modulus with
        | .error fault => .error fault
        | .ok next => buildCldMatrixLoop cld current target width modulus
            (added + 1) next
      else .ok (matrix, added)
    else .ok (matrix, added)
termination_by added _ => target - added
decreasing_by omega

def buildCldMatrix (matrix : LLLMatrix) (cld : Array SparsePolyZZ)
    (current target : Nat) (modulus : ZZ) : RawExec (LLLMatrix × Nat) :=
  buildCldMatrixLoop cld current target (cldSpiralWidth cld) modulus 0 matrix

/-- Descending source while loop. The out-of-range case is unreachable from
shortSpanFromNorms and is retained explicitly in the raw model. -/
def retainedPrefixCount (norms : Array QQ) (bound : QQ) (remaining : Nat) : Nat :=
  if hpositive : 0 < remaining then
    if hindex : remaining - 1 < norms.size then
      if bound < norms[remaining - 1] then
        retainedPrefixCount norms bound (remaining - 1)
      else remaining
    else remaining
  else 0
termination_by remaining

/-- std::iota on the newly allocated row-index vector. -/
def iotaLoop (count index : Nat) (rows : Array Nat) : Array Nat :=
  if hi : index < count then
    iotaLoop count (index + 1) (rows.set! index index)
  else rows
termination_by count - index
decreasing_by omega

def shortSpanFromNorms (norms : Array QQ) (bound : ZZ) : Array Nat :=
  let retained := retainedPrefixCount norms (bound : QQ) norms.size
  iotaLoop retained 0 (Array.replicate retained 0)

/-- In-place coefficient loop before normalization. -/
def truncateTermsLoop (poly : SparsePolyZZ) (divisor : ZZ) (index : Nat) :
    RawExec SparsePolyZZ :=
  if hi : index < poly.size then
    if divisor = 0 then .error .arithmeticDomain
    else truncateTermsLoop
      (poly.set index (poly[index].1, ZZ.fdiv_q 0 poly[index].2 divisor)) divisor (index + 1)
  else .ok poly
termination_by poly.size - index
decreasing_by simp; omega

/-- Each polynomial is normalized immediately after its coefficient loop. -/
def truncateCldLoop (cld : Array SparsePolyZZ) (divisor : ZZ) (index : Nat) :
    RawExec (Array SparsePolyZZ) :=
  if hi : index < cld.size then
    match truncateTermsLoop cld[index] divisor 0 with
    | .error fault => .error fault
    | .ok poly => truncateCldLoop
        (cld.set index (SparsePolyZZ.normalization poly)) divisor (index + 1)
  else .ok cld
termination_by cld.size - index
decreasing_by simp; omega

def truncateCld (cld : Array SparsePolyZZ) (divisor : ZZ) : RawExec (Array SparsePolyZZ) :=
  if 0 < divisor then truncateCldLoop cld divisor 0 else .error .assertionFailure

/-- The repaired LLL interface exports the exact cached final GS norms.
The original individual-short-row return is still computed, as in C++;
the van Hoeij caller instead uses shortSpanFromNorms on the exported norms. -/
def lllReduceWithNorms (execution : LLLExecution) (matrix : LLLMatrix)
    (hinput : execution.inputValid matrix) (bound : ZZ) :
    RawExec (LLLMatrix × LLLMatrix × Array Nat × Array QQ) :=
  match hinitialize : initializeLLL matrix with
  | .error fault => .error fault
  | .ok (mu, norms, transform) =>
    let state := LLLState.mk matrix transform mu norms 1
    match lllMainLoop execution.termination state
        (execution.initialized_valid matrix mu norms transform hinput hinitialize) with
    | .error fault => .error fault
    | .ok reduced =>
      match collectShortRows reduced.matrix bound 0 #[] with
      | .error fault => .error fault
      | .ok rows => .ok (reduced.matrix, reduced.transform, rows, reduced.norms)

end Generated.StrictVanHoeij
'''


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = generate()
    if args.check:
        if not OUT.exists() or OUT.read_text() != source:
            raise SystemExit(f"generated output is stale: {OUT}")
    else:
        OUT.write_text(source)
