"""Explicit parameter-block template; not AST translation or C++ equivalence."""
from pathlib import Path
import argparse

OUT = Path(__file__).resolve().parents[2] / "lean/CLPoly/Generated/StrictVanHoeijParameters.lean"


def generate() -> str:
    return r'''-- Generated by build_strict_vanhoeij_parameters.py; edit the template.
import CLPoly.Generated.StrictVanHoeij

set_option autoImplicit false

namespace Generated.StrictVanHoeijParameters

/-- The source positive ZZ doubling loop. Positivity is an erased invariant. -/
def divisorLoop (height divisor : ZZ) (positive : 0 < divisor) : ZZ :=
  if hlt : divisor * 32 < height then
    divisorLoop height (divisor * 2) (by dsimp only [ZZ] at *; omega)
  else divisor
termination_by (height - divisor).toNat
decreasing_by
  dsimp only [ZZ] at *
  omega

def truncationDivisor (count : Int32) (height modulus : ZZ) : ZZ :=
  let divisor := divisorLoop height 1 (by decide)
  let divisorLimit := divisor * divisor
  let virtualBits : UInt64 := count.toInt64.toUInt64 + 16
  let modulusBits : UInt64 := ZZ.sizeinbase modulus 2
  if modulusBits > virtualBits then
    min divisorLimit (max divisor ((1 : ZZ) <<< (modulusBits - virtualBits).toNat))
  else divisor

structure Parameters where
  divisor : ZZ
  modulus : ZZ
  residual : ZZ
  deriving Repr, BEq

/-- The parameter block after failed singleton validation, including each
precision guard in its source order. Integer `/` is GMP floor division here. -/
def selectParameters (count : Int32) (height originalModulus : ZZ) : Option Parameters :=
  if originalModulus ≤ height then none
  else
    let divisor := truncationDivisor count height originalModulus
    let modulus := originalModulus / divisor
    if modulus ≤ 1 then none
    else
      let residual := (height + divisor - 1) / divisor + 2 * count.toInt
      if modulus ≤ 8 * count.toInt * residual then none
      else some ⟨divisor, modulus, residual⟩

def cldWidthLoop (cld : Array SparsePolyZZ) (index : Nat) (width : Int32) : Int32 :=
  if hi : index < cld.size then
    let poly := cld[index]
    let width := if poly.isEmpty then width else max width ((get_deg poly).toInt32 + 1)
    cldWidthLoop cld (index + 1) width
  else width
termination_by cld.size - index
decreasing_by omega

def cldWidth (cld : Array SparsePolyZZ) : Int32 := cldWidthLoop cld 0 0

end Generated.StrictVanHoeijParameters
'''


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = generate()
    if args.check:
        if not OUT.exists() or OUT.read_text() != source:
            raise SystemExit(f"generated output is stale: {OUT}")
    else:
        OUT.write_text(source)
