"""Source-shaped outer FactorZZ caller of the new retry controller.

This is an explicit control-flow template, not an AST translation proof.
"""
from pathlib import Path
import argparse

OUT = Path(__file__).resolve().parents[2] / "lean/CLPoly/Generated/StrictVanHoeijFactorZZ.lean"


def generate() -> str:
    return r'''-- Generated by build_strict_vanhoeij_factor_zz.py; edit the template.
import CLPoly.Generated.StrictVanHoeijRetry

set_option autoImplicit false

namespace Generated.StrictVanHoeijFactorZZ

/-- Literal outer source branches. The selected-prime proof is erased;
the retry provider supplies arithmetic operations, never factor outputs. -/
def factorSquarefree
    (selectPrime : SparsePolyZZ → Bool → RawExec PrimeSelectionResult)
    (retry : (p : UInt64) → Nat.Prime p.toNat → StrictVanHoeijRetry.RetryExecution)
    (useLargePrime : Bool) (f : SparsePolyZZ)
    (selectedPrime : ∀ selection,
      selectPrime f useLargePrime = .ok selection → Nat.Prime selection.prime.toNat) :
    RawExec (Array SparsePolyZZ) :=
  if f.isEmpty || get_deg f < 2 then .error .assertionFailure
  else
    match hs : selectPrime f useLargePrime with
    | .error fault => .error fault
    | .ok selection =>
      if selection.irreducible || selection.factors.size ≤ 1 then .ok #[f]
      else
        StrictVanHoeijRetry.lllFactorize
          (retry selection.prime (selectedPrime selection hs))
          f selection.factors selection.prime (selectedPrime selection hs).two_le

end Generated.StrictVanHoeijFactorZZ
'''


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = generate()
    if args.check:
        if not OUT.exists() or OUT.read_text() != source:
            raise SystemExit(f"generated output is stale: {OUT}")
    else:
        OUT.write_text(source)
